/**
 * Refreshes src/data/snapshot.ts from the live Sessionize feeds.
 * The snapshot is the fallback used when Sessionize can't be reached.
 *
 *   npm run update-snapshot
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fetchFeeds } from "../src/data/agenda.js";
import type { RawFeeds } from "../src/data/agenda.types.js";

const feeds = await fetchFeeds();

// Keep only the fields the server uses, to keep the bundle small.
const trimmed: RawFeeds = {
  grid: feeds.grid.map((day) => ({
    date: day.date,
    rooms: day.rooms.map((room) => ({
      id: room.id,
      name: room.name,
      sessions: room.sessions.map((session) => ({
        id: session.id,
        title: session.title,
        description: session.description,
        startsAt: session.startsAt,
        endsAt: session.endsAt,
        isServiceSession: session.isServiceSession,
        isPlenumSession: session.isPlenumSession,
        speakers: session.speakers.map((speaker) => ({ id: speaker.id, name: speaker.name })),
        categories: session.categories.map((category) => ({
          id: category.id,
          name: category.name,
          categoryItems: category.categoryItems.map((item) => ({ id: item.id, name: item.name })),
        })),
        roomId: session.roomId,
        room: session.room,
      })),
    })),
  })),
  speakers: feeds.speakers.map((speaker) => ({
    id: speaker.id,
    fullName: speaker.fullName,
    bio: speaker.bio,
    tagLine: speaker.tagLine,
    profilePicture: speaker.profilePicture,
    links: (speaker.links ?? []).map((link) => ({ title: link.title, url: link.url, linkType: link.linkType })),
    sessions: (speaker.sessions ?? []).map((session) => ({ id: session.id, name: session.name })),
  })),
};

const out = fileURLToPath(new URL("../src/data/snapshot.ts", import.meta.url));
const body =
  "// Generated by `npm run update-snapshot` — do not edit by hand.\n" +
  'import type { RawFeeds } from "./agenda.types.js";\n\n' +
  `export const SNAPSHOT: { fetchedAt: string; feeds: RawFeeds } = ${JSON.stringify(
    { fetchedAt: new Date().toISOString(), feeds: trimmed },
    null,
    1,
  )};\n`;
writeFileSync(out, body);

const entries = trimmed.grid.reduce(
  (total, day) => total + day.rooms.reduce((perDay, room) => perDay + room.sessions.length, 0),
  0,
);
console.log(`Wrote ${out}: ${entries} agenda entries, ${trimmed.speakers.length} speakers.`);
